function buildWordIndex(words) {
  var index = {};
  words.forEach(function (word) {
    var seen = {};
    var charIndex;
    var key;
    if (word.length > 4) { return; }
    for (charIndex = 0; charIndex < word.length; charIndex += 1) {
      key = word.charAt(charIndex);
      if (seen[key]) { continue; }
      seen[key] = true;
      if (!index[key]) { index[key] = []; }
      if (index[key].length < 3) { index[key].push(word); }
    }
  });
  return index;
}

