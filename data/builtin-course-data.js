// data/lessons.js —— 出厂自带的零基础课程（离线可用，装好就能学）
//
// 这是产品的**内容主体**。用户每天录的字是「加餐」，这里是她随时能打开就学的东西。
//
// ---- 顺序为什么这么排（每一课都有理由，别随手调） ----
//   1-3   一 二 三 / 十 人 口 / 大 小 上 下
//         起手必须「一秒就懂」：横的数量就是数字，理据不用解释。成就感最重要。
//   4-7   日 月 水 / 火 山 石 / 田 土 木 / 禾 米 果
//         象形独体字。画得出来、能指着实物讲，是她最容易「自己猜对」的一批。
//   8-9   手 目 耳 / 足 头 心
//         身体。她能摸着自己讲，记忆锚点最强。
//   10-11 爸 妈 儿 / 女 子 好
//         家人。情感价值最高的一批，学完能读家里人的称呼。
//   12-16 四 五 六 / 七 八 九 / 百 千 万 / 元 角 分 / 块 斤 毛 两
//         数字和钱。买东西天天用，而且「横的数量」这条线到这里还能继续用。
//   17-20 多 少 不 / 是 有 来 / 去 看 听 / 说 吃 喝
//         生活高频字。这些多数没有字理（虚词），讲字理反而会教错 ——
//         所以 tip 写的是**笔画描述**（「一横一撇一竖，加一点」），
//         零基础阶段「按形状认字」是真实可行的策略。
//   21-25 机 电 话 / 医 院 药 / 买 卖 菜 / 银 存 取 钱 / 走 车 站 票
//         生活主题包：手机 / 医院 / 买菜 / 银行 / 坐车。
//         按**场景**成组，学完一组就能应付一件事。
//
// ---- 每张字卡的四个字段 ----
//   pinyin    拼音。**必须和 data/pinyin.js 一致** —— tools/check_lessons.py 会逐字比对，
//             不一致就报错（手写的拼音一定会漂移，别指望记得住）。
//   words     组词。以词带字：不孤立教字，字卡主体是词。每个词都必须含本字。
//   sentence  例句。日常口语，≤14 字，**必须含本字**（否则她看不出这个字在哪）。
//   tip       讲字理。≤20 字，短句口语。
//             ⚠️ 有字理才写；虚词/简化字没有字理，就写笔画描述。
//                **不要为了填满而编字理** —— 教错了比不教更糟。
//
// ---- 暂时没放进来 ----
//   「行」：多音字（xíng / háng），而 data/pinyin.js 只存主读音 xíng。
//         拿它配「银行」会让字卡上的拼音和组词对不上。等拼音表支持多音字再加。
//   「目 / 足」：现代口语里很少单用，但它们是象形/部首的根，
//         所以留着，例句改成释义（「眼睛也叫目」）而不是硬凑日常句。
//
